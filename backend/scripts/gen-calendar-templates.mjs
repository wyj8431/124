let use = 2400
const lines = []
for (const [, event, tag, items] of events) {
  for (const [title, seed, scene, coverH, height] of items) {
    const w = scene === 16 ? 1920 : scene === 5 ? 900 : scene === 4 ? 1242 : scene === 12 ? 800 : 1080
    const h = scene === 16 ? 1080 : height
    let tagStr = `${event},${tag}`
    if (scene === 10) tagStr += ',手机海报'
    else if (scene === 5) tagStr += ',公众号'
    else if (scene === 4) tagStr += ',小红书'
    else if (scene === 12) tagStr += ',长图'
    else if (scene === 16) tagStr += ',横版'
    lines.push(
      `('${title}', 'https://picsum.photos/seed/${seed}/400/${coverH}', ${scene}, 2, ${w}, ${h}, '{"version":"1.0","layers":[]}', '${tagStr}', ${use}, 1, 1, 1)`,
    )
    use -= 17
  }
}

const out = new URL('../src/main/resources/db/calendar_event_templates.sql', import.meta.url)
fs.writeFileSync(out, lines.join(',\n'))
